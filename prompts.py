def answer_examples(route):
    """같은 라우트의 예시 문항을 (문의, 부른 도구, 모범 답안) 형태로 돌려준다."""
    items = [it for it in _FEWSHOT if it["route"] == route]
    if not items:
        return ""
    lines = ["[같은 유형 응대 예시 — 사실은 예시가 아니라 조회한 조항에서 가져온다]"]
    for it in items:
        tools = ", ".join(it["expected_tools"]) or "없음"
        lines.append(f"- 문의: {it['query']}\n  부른 도구: {tools}\n  답변: {it['reference']}")
    return "\n".join(lines)


